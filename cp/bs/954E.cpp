// =====================================================================================
// WATER TAPS — FULLY COMMENTED REFERENCE SOLUTION
// =====================================================================================

// PROBLEM RECAP
// -------------
// n taps, tap i can deliver x_i in [0, a_i] ml/s at temperature t_i.
// Resulting mixture temperature = (sum x_i*t_i) / (sum x_i).
// We must choose x_i so this equals exactly T, maximizing sum(x_i).

// =====================================================================================
// STEP 0: THE KEY ALGEBRAIC TRICK
// =====================================================================================
// Temperature condition:  (sum x_i t_i) / (sum x_i) = T
//   =>  sum x_i t_i = T * sum x_i
//   =>  sum x_i (t_i - T) = 0

// So instead of thinking in "temperature", think of each tap producing a SIGNED
// quantity x_i*(t_i - T), and these signed quantities must cancel out to 0.

// Classify every tap by comparing t_i to T:
//   - t_i == T  -> contributes 0 regardless of x_i.  FREE volume: just set x_i = a_i.
//                  (stored as eqSum)
//   - t_i >  T  -> "HOT" tap. Contributes POSITIVE amount x_i*(t_i-T).
//   - t_i <  T  -> "COLD" tap. Contributes NEGATIVE amount, i.e. magnitude x_i*(T-t_i).

// Define "pull" of a tap = x_i * |t_i - T|  (always >= 0, how far this tap pushes
// the mixture away from T, weighted by volume).

// For the sum to be zero:
//        (total pull generated by hot taps) == (total pull generated by cold taps)
// Call this common value P (a budget we get to pick, P >= 0).

// The problem now SPLITS into two independent sub-problems joined by a shared P:
//    h(P) = max volume obtainable from HOT taps that generates EXACTLY pull P
//    c(P) = max volume obtainable from COLD taps that generates EXACTLY pull P
// and we want:
//    answer = eqSum + max over P in [0, Pmax] of ( h(P) + c(P) )
// where Pmax = min(max pull hot side can ever generate, max pull cold side can ever
// generate) -- P can't exceed what either side is physically able to match.

// =====================================================================================
// STEP 1: SOLVING h(P) (OR c(P)) FOR A FIXED SIDE -- GREEDY / FRACTIONAL KNAPSACK
// =====================================================================================
// Within one side (say hot), each tap i costs d_i = (t_i - T) "pull" per ml used.
// We want to spend exactly P pull and get max volume => this is fractional knapsack:
// use the CHEAPEST taps first (smallest d_i, i.e. temperature closest to T), because
// they give the most volume per unit of pull spent.

// PROOF SKETCH (exchange argument): if an optimal solution leaves a cheap tap i
// (d_i small) unused/partial while a costlier tap j (d_j > d_i) is used, shifting a
// tiny bit of pull from j to i keeps the same total pull P but strictly increases
// total volume (since 1/d_i > 1/d_j). Contradiction with optimality. So taps must be
// filled in increasing order of d_i.

// THIS MEANS: sort hot taps by (t_i - T) ascending, sort cold taps by (T - t_i)
// ascending, then greedily fill: first tap fully, then next, etc., until the pull
// budget P is exhausted (last tap used only partially/fractionally).

// To evaluate this quickly for ANY P (not just discrete steps), precompute PREFIX
// SUMS after sorting:
//     cap[k]  = total capacity  if the k cheapest taps are FULLY opened
//     pull[k] = total pull      generated if the k cheapest taps are FULLY opened
// These (cap[k], pull[k]) points are the BREAKPOINTS of the piecewise-linear function
// h(P). Between breakpoints, h is linear with slope 1/d_i for the tap being filled.

// Because taps are sorted by increasing d_i, and the "rate" of volume gained per
// unit of pull is 1/d_i, this rate DECREASES as P increases (d_i grows) => h(P) is
// PIECEWISE LINEAR AND CONCAVE. Same logic applies to c(P). This concavity is
// crucial for Step 3 (ternary search).

// =====================================================================================
// STEP 2: EVALUATING h(P) / c(P) AT A SPECIFIC P -- BINARY SEARCH + INTERPOLATION
// =====================================================================================
// Given P, binary-search the prefix-sum "pull[]" array (monotonic non-decreasing)
// to find the smallest index i such that pull[i] >= P. This means:
//   - taps 0..i-1 are all FULLY open (contributing prevCap = cap[i-1] volume and
//     prevPull = pull[i-1] pull)
//   - tap i is only PARTIALLY open, consuming exactly the leftover pull budget
//     (P - prevPull), converted to volume via that tap's own rate d_i.
// Total volume for this P = prevCap + (P - prevPull) / d_i.

// =====================================================================================
// STEP 3: MAXIMIZING h(P) + c(P) OVER P -- TERNARY SEARCH
// =====================================================================================
// h(P) is concave, c(P) is concave => h(P) + c(P) is concave => UNIMODAL on
// [0, Pmax] (rises then falls, single peak, no other local optima).
// This is exactly the condition needed for ternary search: repeatedly narrow
// [lo, hi] by comparing total(P) at two interior points (m1, m2) splitting the
// range into thirds, discarding the third that provably can't contain the peak.
// After enough iterations (300 here, way more than needed), lo ~= hi ~= optimal P.

// Finally re-check a handful of candidate P values (lo, hi, midpoint, 0, Pmax) to
// hedge against floating point drift and take the max -- this is just numerical
// safety, not part of the core algorithm.

// =====================================================================================
// STEP 4: EDGE CASES
// =====================================================================================
// - If there are no hot taps OR no cold taps: it's impossible to generate any
//   nonzero pull that gets cancelled out (nothing on the other side to match it),
//   so hot/cold contribute 0. Answer = eqSum only.
// - If every tap has t_i == T: eqSum captures everything, trivially correct.

// =====================================================================================
// COMPLEXITY
// =====================================================================================
// Sorting: O(n log n). Ternary search: O(300 * log n) evaluations. Overall
// O(n log n) -- easily fast enough for n <= 2*10^5 within 2 seconds.
// =====================================================================================
